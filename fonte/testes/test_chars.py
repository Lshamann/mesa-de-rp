# Testa: etiquetas, busca, versões da ficha e mundos.
import os
HERE = os.path.dirname(os.path.abspath(__file__))
exec(open(os.path.join(HERE, 'mock_claude.py'), encoding='utf-8').read())
URL = 'https://artifact.test/'
ok = lambda c, m: print(('PASS ' if c else 'FAIL ') + m)
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 400, 'height': 820}); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    ev = lambda js: pg.evaluate("async () => { const M = window.__mesa; " + js + " }")
    pg.add_init_script("window.__MESA_TEST = 1;"); pg.add_init_script(MOCK); pg.route('https://fonts.googleapis.com/**', lambda r: r.abort())
    pg.route(URL, lambda r: r.fulfill(status=200, content_type='text/html; charset=utf-8', body=html)); pg.goto(URL); pg.wait_for_timeout(900)
    ok(pg.locator('#lib-q').count() == 0, 'poucos personagens: sem busca')
    ok(pg.locator('#lib-empty').is_visible(), 'biblioteca sem personagens seus mostra a dica de importar')
    # cria 6 personagens com etiquetas
    ev("""for (let i = 0; i < 6; i++) { const c = M.normChar(Object.assign(M.blankChar(), {id: 'c' + i, name: ['Ana','Bruno','Carla','Davi','Eva','Fábio'][i], tagline: 'pessoa ' + i, description: 'desc ' + i, openings: [{id: 'o', label: 'a', text: 'oi'}], tags: i % 2 ? ['mistério', 'noir'] : ['fantasia']})); await M.saveChar(c); M.S.chars.set(c.id, c); } M.renderLibrary();""")
    pg.wait_for_timeout(300)
    ok(pg.locator('#lib-q').count() == 1, 'com mais de 6 personagens aparece a busca')
    ok(pg.locator('.tagrow .chip').count() == 3, 'chips de etiqueta: ' + str(pg.locator('.tagrow .chip').count()))
    pg.fill('#lib-q', 'carla'); pg.wait_for_timeout(200)
    ok(pg.locator('#g-mine .pc').count() == 1 and 'Carla' in pg.inner_text('#g-mine'), 'busca por nome filtra')
    pg.fill('#lib-q', 'MISTERIO'); pg.wait_for_timeout(200)
    ok(pg.locator('#g-mine .pc').count() == 3, 'busca por etiqueta sem acento e maiúscula: ' + str(pg.locator('#g-mine .pc').count()))
    pg.fill('#lib-q', ''); pg.click('.tagrow .chip >> text=#fantasia'); pg.wait_for_timeout(300)
    ok(pg.locator('#g-mine .pc').count() == 3 and pg.locator('#lib-q').count() == 1, 'chip filtra e mantém a busca')
    pg.click('.tagrow .chip.on'); pg.wait_for_timeout(300)
    ok(pg.locator('#g-mine .pc').count() == 6, 'tocar de novo no chip limpa o filtro')
    # versões da ficha
    pg.click('[data-act=edit][data-id=c0]'); pg.wait_for_timeout(400)
    ok(pg.input_value('#e-tags') == 'fantasia', 'etiquetas aparecem no editor')
    pg.fill('#e-desc', 'descrição NOVA versão 2'); pg.fill('#e-tags', 'fantasia, drama'); pg.click('#e-save'); pg.wait_for_timeout(500)
    pg.click('[data-act=edit][data-id=c0]'); pg.wait_for_timeout(400)
    ok(pg.locator('details.adv summary', has_text='Versões anteriores').count() == 1, 'versão anterior guardada')
    pg.fill('#e-desc', 'descrição versão 3'); pg.click('#e-save'); pg.wait_for_timeout(500)
    pg.click('[data-act=edit][data-id=c0]'); pg.wait_for_timeout(400)
    n = pg.evaluate("window.__mesa.S.chars.get('c0').hist.length"); ok(n == 2, 'duas versões guardadas: %d' % n)
    pg.locator('details.adv summary', has_text='Versões anteriores').click(); pg.locator('[data-act=hist-restore]').nth(1).click(); pg.wait_for_timeout(300)
    ok(pg.input_value('#e-desc') == 'desc 0', 'restaurar a mais antiga traz o texto original: ' + pg.input_value('#e-desc'))
    pg.click('#e-cancel'); pg.wait_for_timeout(300)
    ok(pg.evaluate("window.__mesa.S.chars.get('c0').description") == 'descrição versão 3', 'cancelar não altera o salvo')
    pg.click('[data-act=edit][data-id=c0]'); pg.wait_for_timeout(300)
    pg.click('#e-save'); pg.wait_for_timeout(400)
    ok(pg.evaluate("window.__mesa.S.chars.get('c0').hist.length") == 2, 'salvar sem mudar não cria versão repetida')
    # mundos
    pg.click('[data-act=new-world]'); pg.wait_for_timeout(400)
    ok(not pg.locator('#e-desc').is_visible() and pg.locator('#e-tags').count() == 0 and pg.locator('[data-act=add-lo]').count() == 1, 'editor de mundo mostra só básico e lorebook')
    pg.fill('#e-name', 'Ilha de Pedra'); pg.click('[data-act=add-lo]'); pg.wait_for_timeout(200)
    pg.fill('#lo-n-0', 'Farol'); pg.fill('#lo-k-0', 'farol'); pg.fill('#lo-c-0', 'O farol da Ilha de Pedra está apagado há vinte anos.'); pg.check('#lo-a-0')
    pg.click('#e-save'); pg.wait_for_timeout(500)
    ok(pg.locator('#g-mine .pc', has_text='Ilha de Pedra').count() == 0 and 'mundos' in pg.inner_text('#lib').lower(), 'mundo aparece na seção Mundos, não entre personagens')
    ok(pg.locator('[data-act=quick][data-id=c1]').count() == 1 and pg.locator('.pc', has_text='Ilha de Pedra').locator('[data-act=quick]').count() == 0, 'mundo não tem botão Jogar')
    pg.click('[data-act=edit][data-id=c1]'); pg.wait_for_timeout(400)
    ok(pg.locator('#e-world').count() == 1, 'ficha do personagem oferece o campo Mundo')
    wid = pg.evaluate("[...window.__mesa.S.chars.values()].find(c => c.role === 'world').id")
    pg.select_option('#e-world', wid); pg.click('#e-save'); pg.wait_for_timeout(500)
    ok('ilha de pedra' in pg.inner_text('[data-id=c1]').lower(), 'cartão mostra o mundo do personagem')
    pg.click('[data-act=quick][data-id=c1]'); pg.wait_for_timeout(1500)
    r = pg.evaluate("() => { const M = window.__mesa; const t = M.buildTurns(M.S.story, M.S.char, M.S.story.messages.length).turns; return t[0].content; }")
    ok('farol da Ilha de Pedra' in r, 'lore do mundo entra no prompt do personagem')
    pg.click('#b-memory'); pg.wait_for_timeout(300)
    opts = pg.evaluate("[...document.querySelectorAll('#cast-pick option')].map(o => o.textContent)")
    ok('Ilha de Pedra' not in opts, 'mundo não aparece como opção de elenco')
    print('errors', errs)
